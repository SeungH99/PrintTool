/**
 * ICC-based CMYK ⇄ sRGB conversion plus hex/rgb helpers. The conversion is driven
 * by a real CMYK ICC profile through Little-CMS (lcms-wasm), so results are accurate
 * to the chosen profile rather than a naive formula. This module is environment-
 * agnostic: it takes an already-instantiated lcms object + the lcms constants + the
 * profile bytes, so it runs the same in Node (tests) and in the browser.
 */

export type RGB = [number, number, number];
export type CMYK = [number, number, number, number];

const clampByte = (n: number) => Math.max(0, Math.min(255, Math.round(n)));
const clampPct = (n: number) => Math.max(0, Math.min(100, n));

/** "#1a2b3c" / "1a2b3c" → [r,g,b], or null when not a valid 6/3-digit hex. */
export function hexToRgb(hex: string): RGB | null {
  const h = hex.trim().replace(/^#/, '');
  const full = h.length === 3 ? h.replace(/(.)/g, '$1$1') : h;
  if (!/^[0-9a-fA-F]{6}$/.test(full)) return null;
  return [
    parseInt(full.slice(0, 2), 16),
    parseInt(full.slice(2, 4), 16),
    parseInt(full.slice(4, 6), 16),
  ];
}

export function rgbToHex(r: number, g: number, b: number): string {
  const hex = (n: number) => clampByte(n).toString(16).padStart(2, '0');
  return `#${hex(r)}${hex(g)}${hex(b)}`;
}

/** The lcms-wasm named constants this engine needs (imported by the caller). */
export interface LcmsConstants {
  INTENT_RELATIVE_COLORIMETRIC: number;
  cmsFLAGS_NOCACHE: number;
  cmsFLAGS_HIGHRESPRECALC: number;
  cmsFLAGS_NOOPTIMIZE: number;
  cmsFLAGS_BLACKPOINTCOMPENSATION: number;
  cmsInfoDescription: number;
}

/** Minimal surface of the instantiated lcms-wasm object used here. */
export interface Lcms {
  cmsOpenProfileFromMem: (data: Uint8Array, len: number) => number;
  cmsCreate_sRGBProfile: () => number;
  cmsGetProfileInfoASCII: (p: number, info: number, lang: string, country: string) => string;
  cmsFormatterForColorspaceOfProfile: (p: number, bytes: number, isFloat: boolean) => number;
  cmsCreateTransform: (
    inP: number,
    inFmt: number,
    outP: number,
    outFmt: number,
    intent: number,
    flags: number,
  ) => number;
  cmsDoTransform: (t: number, data: Uint8ClampedArray, nPixels: number) => Uint8ClampedArray;
  cmsCloseProfile: (p: number) => void;
}

export interface ColorEngine {
  profileName: string;
  cmykToRgb: (c: number, m: number, y: number, k: number) => RGB;
  rgbToCmyk: (r: number, g: number, b: number) => CMYK;
  /**
   * Soft-proof a whole image in one shot: round-trip a packed RGB buffer
   * (3 bytes/pixel, `nPixels` pixels) through CMYK and back, returning the
   * simulated RGB. Runs as two bulk Little-CMS transforms, not per-pixel JS.
   */
  proofImage: (rgb: Uint8ClampedArray, nPixels: number) => Uint8ClampedArray;
}

/**
 * How far an sRGB colour shifts when forced through the CMYK profile and back.
 * A large distance means the colour sits outside the printable gamut (it got
 * clipped); near-neutral, in-gamut colours round-trip almost exactly.
 */
export function gamutClipDistance(engine: ColorEngine, [r, g, b]: RGB): number {
  const cmyk = engine.rgbToCmyk(r, g, b);
  const back = engine.cmykToRgb(cmyk[0], cmyk[1], cmyk[2], cmyk[3]);
  return Math.hypot(r - back[0], g - back[1], b - back[2]);
}

/**
 * Build a CMYK⇄sRGB engine from a CMYK ICC profile. sRGB is generated by Little-CMS,
 * so only the one CMYK profile must be supplied.
 */
export function buildEngine(
  lcms: Lcms,
  k: LcmsConstants,
  cmykProfileBytes: Uint8Array,
): ColorEngine {
  const cmyk = lcms.cmsOpenProfileFromMem(cmykProfileBytes, cmykProfileBytes.length);
  if (!cmyk) throw new Error('Could not open CMYK profile');
  const srgb = lcms.cmsCreate_sRGBProfile();
  const cmykFmt = lcms.cmsFormatterForColorspaceOfProfile(cmyk, 1, false);
  const rgbFmt = lcms.cmsFormatterForColorspaceOfProfile(srgb, 1, false);
  const intent = k.INTENT_RELATIVE_COLORIMETRIC;
  const flags =
    k.cmsFLAGS_NOCACHE |
    k.cmsFLAGS_HIGHRESPRECALC |
    k.cmsFLAGS_NOOPTIMIZE |
    k.cmsFLAGS_BLACKPOINTCOMPENSATION;

  const toRgb = lcms.cmsCreateTransform(cmyk, cmykFmt, srgb, rgbFmt, intent, flags);
  const toCmyk = lcms.cmsCreateTransform(srgb, rgbFmt, cmyk, cmykFmt, intent, flags);
  const profileName = lcms.cmsGetProfileInfoASCII(cmyk, k.cmsInfoDescription, 'en', 'US');
  lcms.cmsCloseProfile(cmyk);
  lcms.cmsCloseProfile(srgb);

  return {
    profileName,
    cmykToRgb(c, m, y, k2) {
      const data = new Uint8ClampedArray([
        Math.round((clampPct(c) / 100) * 255),
        Math.round((clampPct(m) / 100) * 255),
        Math.round((clampPct(y) / 100) * 255),
        Math.round((clampPct(k2) / 100) * 255),
      ]);
      const out = lcms.cmsDoTransform(toRgb, data, 1);
      return [out[0], out[1], out[2]];
    },
    rgbToCmyk(r, g, b) {
      const data = new Uint8ClampedArray([clampByte(r), clampByte(g), clampByte(b)]);
      const out = lcms.cmsDoTransform(toCmyk, data, 1);
      return [
        Math.round((out[0] / 255) * 100),
        Math.round((out[1] / 255) * 100),
        Math.round((out[2] / 255) * 100),
        Math.round((out[3] / 255) * 100),
      ];
    },
    proofImage(rgb, nPixels) {
      const cmyk = lcms.cmsDoTransform(toCmyk, rgb, nPixels);
      return lcms.cmsDoTransform(toRgb, cmyk, nPixels);
    },
  };
}
